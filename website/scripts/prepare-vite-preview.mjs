import { access, cp, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const websiteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const nitroServerEntry = path.join(websiteRoot, ".output/server/index.mjs");
const publicDir = path.join(websiteRoot, ".output/public");
const clientDir = path.join(websiteRoot, "dist/client");
const shimDir = path.join(websiteRoot, "dist/server");
const shimPath = path.join(shimDir, "server.js");

async function exists(candidate) {
  try {
    await access(candidate);
    return true;
  } catch {
    return false;
  }
}

if (!(await exists(nitroServerEntry)) || !(await exists(path.join(publicDir, "index.html")))) {
  console.error(
    "Production build output is missing. Run `bun run build` in the website folder, then retry preview.",
  );
  process.exit(1);
}

await cp(publicDir, clientDir, { recursive: true, force: true });

let vars = {};
try {
  const wrangler = JSON.parse(
    await readFile(path.join(websiteRoot, ".output/server/wrangler.json"), "utf8"),
  );
  if (wrangler.vars && typeof wrangler.vars === "object" && !Array.isArray(wrangler.vars)) {
    vars = wrangler.vars;
  }
} catch {
  /* Optional Cloudflare vars for local preview. */
}

const entrySpecifier = path
  .relative(shimDir, nitroServerEntry)
  .split(path.sep)
  .join("/");
const importPath = entrySpecifier.startsWith(".") ? entrySpecifier : `./${entrySpecifier}`;

const source = `// Generated by scripts/prepare-vite-preview.mjs for local \`vite preview\`.
import server from "${importPath}";

const env = ${JSON.stringify(vars)};
const ctx = { waitUntil() {}, passThroughOnException() {}, props: {} };

export default {
  fetch(request) {
    Object.defineProperty(request, "ip", { value: undefined, writable: true, configurable: true });
    return server.fetch(request, env, ctx);
  },
};
`;

await mkdir(shimDir, { recursive: true });
await writeFile(shimPath, source);
console.log("Prepared local preview: dist/client (static) and dist/server/server.js (SSR shim).");
